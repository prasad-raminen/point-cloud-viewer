using PointCloudViewer.Core;
using PointCloudViewer.Core.Domain;
using PointCloudViewer.Core.Parsing;

namespace PointCloudViewer.Tests.Parsing;

public class PlyParserTests
{
    private readonly PlyParser _parser = new();

    [Fact]
    public async Task Parses_ascii_ply_with_uchar_colours()
    {
        const string ply = """
            ply
            format ascii 1.0
            comment generated by a test
            element vertex 2
            property float x
            property float y
            property float z
            property uchar red
            property uchar green
            property uchar blue
            end_header
            0 0 0 255 0 0
            1.5 2 -3 0 128 255
            """;

        var result = await _parser.ParseAsync(ply);

        Assert.Equal("ply", result.Format);
        Assert.True(result.Cloud.HasColor);
        Assert.Equal(
            [new PointRecord(0, 0, 0, 255, 0, 0), new PointRecord(1.5, 2, -3, 0, 128, 255)],
            result.Cloud.Points);
    }

    [Fact]
    public async Task Scales_float_colours_from_unit_range()
    {
        const string ply = """
            ply
            format ascii 1.0
            element vertex 1
            property double x
            property double y
            property double z
            property float red
            property float green
            property float blue
            end_header
            1 2 3 1.0 0.5 0
            """;

        var result = await _parser.ParseAsync(ply);

        Assert.Equal(new PointRecord(1, 2, 3, 255, 128, 0), Assert.Single(result.Cloud.Points));
    }

    [Fact]
    public async Task Reads_properties_by_name_regardless_of_order_and_ignores_unknown_ones()
    {
        const string ply = """
            ply
            format ascii 1.0
            element vertex 1
            property float nx
            property float z
            property float intensity
            property float y
            property float x
            end_header
            0.1 30 7 20 10
            """;

        var result = await _parser.ParseAsync(ply);

        Assert.False(result.Cloud.HasColor);
        Assert.Equal(PointRecord.Uncolored(10, 20, 30), Assert.Single(result.Cloud.Points));
    }

    [Fact]
    public async Task Stops_after_declared_vertices_and_ignores_face_element()
    {
        const string ply = """
            ply
            format ascii 1.0
            element vertex 3
            property float x
            property float y
            property float z
            element face 1
            property list uchar int vertex_indices
            end_header
            0 0 0
            1 0 0
            0 1 0
            3 0 1 2
            """;

        var result = await _parser.ParseAsync(ply);

        Assert.Equal(3, result.Cloud.Count);
        Assert.Equal(0, result.SkippedLines);
    }

    [Fact]
    public async Task Skips_elements_declared_before_vertex()
    {
        const string ply = """
            ply
            format ascii 1.0
            element camera 2
            property float fov
            element vertex 1
            property float x
            property float y
            property float z
            end_header
            60
            75
            4 5 6
            """;

        var result = await _parser.ParseAsync(ply);

        Assert.Equal(PointRecord.Uncolored(4, 5, 6), Assert.Single(result.Cloud.Points));
    }

    [Fact]
    public async Task Skips_malformed_vertex_lines_and_warns_on_truncated_file()
    {
        const string ply = """
            ply
            format ascii 1.0
            element vertex 5
            property float x
            property float y
            property float z
            end_header
            1 2 3
            1 2
            a b c
            4 5 6
            """;

        var result = await _parser.ParseAsync(ply);

        Assert.Equal(2, result.Cloud.Count);
        Assert.Equal(2, result.SkippedLines);
        Assert.Contains(result.Warnings, w => w.StartsWith("Line 9:", StringComparison.Ordinal));
        Assert.Contains(result.Warnings, w => w.StartsWith("Line 10:", StringComparison.Ordinal));
        Assert.Contains(result.Warnings, w => w.Contains("4 of 5", StringComparison.Ordinal));
    }

    [Theory]
    [InlineData("binary_little_endian")]
    [InlineData("binary_big_endian")]
    public async Task Rejects_binary_encodings_as_unsupported(string encoding)
    {
        var ply = $"ply\nformat {encoding} 1.0\nelement vertex 0\nend_header\n";

        await Assert.ThrowsAsync<UnsupportedPointCloudFormatException>(() => _parser.ParseAsync(ply));
    }

    [Theory]
    [InlineData("not a ply file\n")]
    [InlineData("ply\nformat ascii 1.0\nelement vertex 1\nproperty float x\n")]
    [InlineData("ply\nformat ascii 1.0\nelement vertex 1\nproperty float x\nproperty float y\nend_header\n1 2\n")]
    [InlineData("ply\nformat ascii 1.0\nelement face 1\nend_header\n")]
    [InlineData("ply\nelement vertex 1\nproperty float x\nproperty float y\nproperty float z\nend_header\n1 2 3\n")]
    [InlineData("ply\nformat ascii 1.0\nelement vertex many\nend_header\n")]
    [InlineData("ply\nformat ascii 1.0\nelement vertex 1\nproperty quaternion x\nend_header\n")]
    public async Task Rejects_structurally_invalid_headers(string ply)
    {
        await Assert.ThrowsAsync<InvalidPointCloudException>(() => _parser.ParseAsync(ply));
    }

    [Fact]
    public async Task Rejects_header_that_declares_more_vertices_than_the_limit()
    {
        const string ply = "ply\nformat ascii 1.0\nelement vertex 1000\nproperty float x\nproperty float y\nproperty float z\nend_header\n";

        await Assert.ThrowsAsync<PointLimitExceededException>(
            () => _parser.ParseAsync(ply, new ParseOptions { MaxPoints = 10 }));
    }
}
